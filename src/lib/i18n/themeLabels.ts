import type { TFunction } from 'i18next';

/** Translate registered UI roles, retaining labels for user-defined CSS and tokens. */
export function themeBindingLabel(binding: { key: string; token: string; label: string; kind?: string }, t: TFunction): string {
  if (binding.kind === 'css') return /^css:(?:generated|\d+):[a-z-]+$/.test(binding.key) ? t('messages:themeInspection.fixedColor') : binding.label;
  const token = binding.token.split('←')[0].trim().replace(/^--/, '');
  if (token.startsWith('color-article-')) return t(`dialogs:articleColors.${token}`, { defaultValue: binding.label });
  if (binding.key.startsWith('node:')) return t('dialogs:templates.nodeColor', {
    node: t(`dialogs:nodes.${binding.key.slice(5)}`, { defaultValue: binding.key.slice(5) }),
  });
  if (binding.key.startsWith('surface:')) return t(`dialogs:surfaceRoles.${token}`, { defaultValue: binding.label });
  return t(`dialogs:colorRoles.${binding.key}`, { defaultValue: binding.label });
}

/** Location metadata is generated by the inspector; authored token strings stay unchanged. */
export function themeBindingToken(binding: { key: string; token: string; kind?: string }, t: TFunction): string {
  if (binding.kind !== 'css' || !/^css:(?:generated|\d+):[a-z-]+$/.test(binding.key)) return binding.token;
  if (binding.key.startsWith('css:generated:')) return t('messages:themeInspection.generatedStyles');
  const line = /^CSS · 第 (\d+) 行$/.exec(binding.token)?.[1];
  return line ? t('messages:themeInspection.cssLine', { line }) : binding.token;
}
