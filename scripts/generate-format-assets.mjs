import fs from 'node:fs';
import path from 'node:path';
import ts from 'typescript';
import crypto from 'node:crypto';
import { build as bundle, version as esbuildVersion } from 'esbuild';

const root = process.cwd();
// Only this explicitly public preset is bundled. Never enumerate sibling presets.
const algorithmRoot = path.join(root, 'resources/presets/platform/wechat-article/format/algorithms');
const algorithmManifest = JSON.parse(fs.readFileSync(path.join(algorithmRoot, 'manifest.json'), 'utf8'));
const algorithmFiles = {};
for (const component of algorithmManifest.components) {
  for (const file of [...component.scripts, component.license]) {
    if (!/^[a-zA-Z0-9][a-zA-Z0-9._/-]*$/.test(file.path) || file.path.split('/').includes('..')) throw new Error('Invalid public algorithm path');
    const bytes = fs.readFileSync(path.join(algorithmRoot, file.path));
    if (crypto.createHash('sha256').update(bytes).digest('hex') !== file.sha256) throw new Error('Public algorithm hash mismatch: ' + file.path);
    algorithmFiles[file.path] = bytes.toString('utf8');
  }
}
const canonical = value => JSON.stringify((function normalize(item) {
  return Array.isArray(item) ? item.map(normalize) : item && typeof item === 'object' ? Object.fromEntries(Object.entries(item).sort(([a], [b]) => a.localeCompare(b)).map(([key, val]) => [key, normalize(val)])) : item;
})(value));
const algorithmPackage = { manifest: algorithmManifest, files: algorithmFiles };
algorithmPackage.fingerprint = crypto.createHash('sha256').update(canonical(algorithmPackage)).digest('hex');
const algorithmTarget = path.join(root, 'resources/presets/platform/wechat-article/algorithms.generated.json');
const algorithmData = JSON.stringify(algorithmPackage, null, 2) + '\n';
if (!fs.existsSync(algorithmTarget) || fs.readFileSync(algorithmTarget, 'utf8') !== algorithmData) fs.writeFileSync(algorithmTarget, algorithmData);
function compile(file) {
  const source = fs.readFileSync(path.join(root, file), 'utf8');
  return ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.ESNext } }).outputText
    .replace(/^import \{ FRAME_MESSAGES \} from ['"]\.\/frameMessages['"];\s*$/gm, '')
    .replace(/^import \{ articleDarkMode \} from ['"]\.\/styleTypes['"];\s*$/gm, '')
    .replace(/^export (?=function|async function)/gm, '');
}
const messages = JSON.parse(fs.readFileSync(path.join(root, 'resources/locale/zh-CN/messages.json'), 'utf8')).frame;
const output = `// Generated by scripts/generate-format-assets.mjs from the shared TypeScript sources.\n(() => {\nconst FRAME_MESSAGES = ${JSON.stringify(messages)};\n${compile('src/lib/article-format/colors.ts')}\nwindow.ArticleColorNormalizer = createArticleColorNormalizer;\n${compile('src/lib/article-format/styleTypes.ts')}\n${compile('src/lib/article-format/bootstrap.ts')}\nvoid runFormatFrameBootstrap();\n})();\n`;
const target = path.join(root, 'public/format/article-format-bootstrap.js');
if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) fs.writeFileSync(target, output);
const mermaidOutput = '// Generated from src/lib/article-format/mermaidFrame.ts.\n(() => {\n' + compile('src/lib/article-format/mermaidFrame.ts') + '\nvoid runMermaidFrameBootstrap();\n})();\n';
const mermaidTarget = path.join(root, 'public/format/article-mermaid-bootstrap.js');
if (!fs.existsSync(mermaidTarget) || fs.readFileSync(mermaidTarget, 'utf8') !== mermaidOutput) fs.writeFileSync(mermaidTarget, mermaidOutput);
const diagram = JSON.parse(fs.readFileSync(path.join(root, 'resources/render/mermaid.json'), 'utf8'));
const diagramEntry = 'node_modules/mermaid/dist/mermaid.core.mjs';
if (crypto.createHash('sha256').update(fs.readFileSync(path.join(root, diagramEntry))).digest('hex') !== diagram.sourceSha256
  || JSON.parse(fs.readFileSync(path.join(root, 'node_modules/mermaid/package.json'))).version !== diagram.version
  || JSON.parse(fs.readFileSync(path.join(root, 'node_modules/katex/package.json'))).version !== diagram.katex
  || esbuildVersion !== diagram.esbuild) throw new Error('Mermaid build inputs changed; review and repin');
// Rebundle locked official modules: the vendor's prebuilt IIFE contains an older KaTeX.
const diagramBuild = await bundle({ entryPoints: [diagramEntry], bundle: true, write: false, platform: 'browser', target: 'es2020', format: 'iife', globalName: 'ArticleMermaid', minify: true, legalComments: 'eof', footer: { js: 'globalThis.mermaid = ArticleMermaid.default;' } });
const diagramBytes = diagramBuild.outputFiles[0].contents;
const diagramHash = crypto.createHash('sha256').update(diagramBytes).digest('hex');
if (diagram.sha256 && diagramHash !== diagram.sha256) throw new Error('Mermaid bundle output changed; review and repin');
const diagramTarget = path.join(root, 'public/algorithm/mermaid/mermaid.min.js');
fs.mkdirSync(path.dirname(diagramTarget), { recursive: true });
if (!fs.existsSync(diagramTarget) || !fs.readFileSync(diagramTarget).equals(Buffer.from(diagramBytes))) fs.writeFileSync(diagramTarget, diagramBytes);
// The official dist chunks also inline dependencies. Carry the locked runtime tree's
// original notices, including those whose package is not a separate bundle input.
const diagramLicenses = [], visitedPackages = new Set();
function collectDiagramLicenses(packageRoot) {
  if (visitedPackages.has(packageRoot)) return;
  visitedPackages.add(packageRoot);
  const metadata = JSON.parse(fs.readFileSync(path.join(packageRoot, 'package.json'), 'utf8'));
  const notices = fs.readdirSync(packageRoot).filter(name => /^(?:licen[sc]e|copying)(?:[._-].*)?$/i.test(name) && fs.statSync(path.join(packageRoot, name)).isFile());
  if (!notices.length) throw new Error('Missing Mermaid dependency license: ' + metadata.name);
  for (const name of notices) {
    const relative = path.posix.join('public/licenses/mermaid/dependencies', metadata.name, metadata.version, name);
    const bytes = fs.readFileSync(path.join(packageRoot, name)); const target = path.join(root, relative);
    fs.mkdirSync(path.dirname(target), { recursive: true });
    if (!fs.existsSync(target) || !fs.readFileSync(target).equals(bytes)) fs.writeFileSync(target, bytes);
    diagramLicenses.push({ package: metadata.name, version: metadata.version, license: metadata.license, path: relative, sha256: crypto.createHash('sha256').update(bytes).digest('hex') });
  }
  for (const dependency of Object.keys(metadata.dependencies ?? {})) {
    let cursor = packageRoot, found;
    while (cursor.startsWith(root)) {
      const candidate = path.join(cursor, 'node_modules', dependency);
      if (fs.existsSync(path.join(candidate, 'package.json'))) { found = candidate; break; }
      const parent = path.dirname(cursor); if (parent === cursor) break; cursor = parent;
    }
    if (!found) throw new Error('Missing Mermaid runtime dependency: ' + dependency);
    collectDiagramLicenses(found);
  }
}
collectDiagramLicenses(path.join(root, 'node_modules/mermaid'));
diagramLicenses.sort((a, b) => a.path.localeCompare(b.path));
const licenseIndex = path.join(root, 'resources/render/mermaid-licenses.json'), licenseData = JSON.stringify(diagramLicenses, null, 2) + '\n';
if (!fs.existsSync(licenseIndex) || fs.readFileSync(licenseIndex, 'utf8') !== licenseData) fs.writeFileSync(licenseIndex, licenseData);
